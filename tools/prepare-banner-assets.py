wash = dict(zip(order, list(range(105, 132, 2)) + [13]))
entries = []

def add(key, title, body, mood, dark=None, light=None):
    item = dict(key=key, title=title, body=body, mood=mood, art=None)
    if dark is not None:
        item["art"] = "banner_" + key.lower()
        item["sources"] = {}
        for theme, index in [("dark", dark), ("light", light)]:
            source = FILES[index]
            target = OUT / f'{item["art"]}_{theme}.png'
            shutil.copyfile(source, target)
            item["sources"][theme] = dict(file=source.relative_to(ROOT).as_posix(), sha256=hashlib.sha256(source.read_bytes()).hexdigest())
    entries.append(item)


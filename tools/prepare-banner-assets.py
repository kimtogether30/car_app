def quoted(value):
    return "null" if value is None else json.dumps(value, ensure_ascii=False)
lines = ["package com.vemoring.companion", "", "// Generated by tools/prepare-banner-assets.py from the supplied design/banner artwork.",
    "data class BannerDefinition(val key: String, val title: String, val body: String, val mood: String, val art: String? = null)",
    "object BannerCatalog {", "    val entries: Map<String, BannerDefinition> = listOf("]
for e in entries:
    lines.append("        BannerDefinition("+", ".join(quoted(e[k]) for k in ["key", "title", "body", "mood", "art"])+"),")
lines += ["    ).associateBy { it.key }", "    operator fun get(key: String): BannerDefinition = entries.getValue(key)", "}", ""]
(ROOT / "companion/src/main/kotlin/com/vemoring/companion/BannerCatalog.kt").write_text("\n".join(lines), encoding="utf-8")
